#!/usr/bin/env node
/**
 * @trongtin1/agent-template CLI
 * Commands: init, update [--dry-run], sync
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';
import readline from 'readline/promises';
import { TARGETS, parseTargets, sync } from '../.agents/scripts/sync_targets.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = path.resolve(__dirname, '..');
const AGENTS_SRC = path.join(PACKAGE_ROOT, '.agents');

const [, , command, ...args] = process.argv;
const isDryRun = args.includes('--dry-run');
const targetFlag = (() => {
  const i = args.findIndex(a => a === '--target' || a === '-t');
  if (i > -1) return args[i + 1];
  return args.find(a => a.startsWith('--target='))?.split('=')[1];
})();
const STATE = path.join('.agents', '.agent-kit', 'generated.json');

// ── Helpers ──────────────────────────────────────────────────────────────────

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.name === 'generated.json') continue;
    if (entry.isDirectory()) {
      copyDir(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function getAllFiles(dir, base = dir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.name === 'generated.json') continue;
    if (entry.isDirectory()) {
      results.push(...getAllFiles(full, base));
    } else {
      results.push(path.relative(base, full));
    }
  }
  return results;
}

function getGitModifiedFiles() {
  try {
    const result = execSync('git status --porcelain', {
      stdio: ['pipe', 'pipe', 'pipe'],
    }).toString();
    const modified = new Set();
    for (const line of result.split('\n')) {
      if (!line.trim()) continue;
      const entry = line.slice(3).trim().replace(/^"|"$/g, '');
      const parts = entry.split(' -> ');
      const target = parts[parts.length - 1];
      modified.add(path.normalize(target));
    }
    return modified;
  } catch {
    return new Set();
  }
}

const IDE_MARKERS = { claude: ['.claude', 'CLAUDE.md'], cursor: ['.cursor'], vscode: ['.vscode', '.github/copilot-instructions.md'], codex: ['AGENTS.md', '.codex'], antigravity: ['.gemini'] };

function detectTargets(cwd) {
  return Object.keys(IDE_MARKERS).filter(t => IDE_MARKERS[t].some(m => fs.existsSync(path.join(cwd, m))));
}

async function chooseTargets(cwd) {
  if (targetFlag !== undefined) return parseTargets(targetFlag);
  const detected = detectTargets(cwd);
  if (!process.stdin.isTTY || !process.stdout.isTTY) {
    if (detected.length) { info(`Detected: ${detected.join(', ')} (override with --target)`); return detected; }
    warn('No --target given. Installing only the native .agents/ layer.');
    info(`Choose IDEs with: --target ${Object.keys(TARGETS).join('|')}|all (comma-separated)`);
    return ['antigravity'];
  }
  const keys = Object.keys(TARGETS);
  log('Which IDE(s) will you use?');
  keys.forEach((k, i) => log(`  ${i + 1}) ${TARGETS[k]}${detected.includes(k) ? '  (detected)' : ''}`));
  log(`  ${keys.length + 1}) All`);
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const answer = (await rl.question('Enter numbers separated by commas: ')).trim();
  rl.close();
  const picks = answer.split(',').map(n => Number(n.trim())).filter(Boolean);
  if (picks.includes(keys.length + 1)) return keys;
  const chosen = picks.map(n => keys[n - 1]).filter(Boolean);
  return chosen.length ? chosen : (detected.length ? detected : ['antigravity']);
}

function runSync(cwd, targets) {
  const res = sync(cwd, targets);
  ok(`Generated IDE files for: ${targets.map(t => TARGETS[t]).join(', ')} (${res.files} files)`);
  for (const f of res.skipped) warn(`skipped ${f} — already exists and was not generated by Agent Kit`);
}

function log(msg) { console.log(msg); }
function ok(msg)  { console.log(`\x1b[32m✅ ${msg}\x1b[0m`); }
function warn(msg){ console.log(`\x1b[33m⚠️  ${msg}\x1b[0m`); }
function info(msg){ console.log(`\x1b[36mℹ️  ${msg}\x1b[0m`); }
function err(msg) { console.error(`\x1b[31m❌ ${msg}\x1b[0m`); }

// ── Commands ──────────────────────────────────────────────────────────────────

async function cmdInit() {
  const cwd = process.cwd();
  const destAgents = path.join(cwd, '.agents');

  log('\n🤖 agent-template init\n');

  if (!fs.existsSync(AGENTS_SRC)) {
    err('Source .agents/ not found in package. Please reinstall.');
    process.exit(1);
  }

  if (fs.existsSync(destAgents)) {
    warn('.agents/ already exists in this project.');
    warn('Run "npx @trongtin1/agent-template update" to update it, or "sync --target <ide>" to add an IDE.');
    process.exit(0);
  }

  let targets;
  try {
    targets = await chooseTargets(cwd);
  } catch (e) {
    err(e.message);
    process.exit(1);
  }

  log('📂 Installing .agents/ into current project...');
  copyDir(AGENTS_SRC, destAgents);

  log('');
  runSync(cwd, targets);
  ok('.agents/ installed successfully!');
  log('');
  info('Next steps:');
  log('  1. Open this folder in your IDE (the files for the chosen IDE(s) were generated).');
  log('  2. Slash commands like /plan, /commit, /orchestrate are now available.');
  log('  3. Run: npm run check:agents  (if you copied package.json scripts too)');
  log('');
  info('To update later: npx @trongtin1/agent-template update');
  log('');
}

async function cmdSync() {
  const cwd = process.cwd();
  if (!fs.existsSync(path.join(cwd, '.agents'))) {
    err('No .agents/ found. Run "npx @trongtin1/agent-template init" first.');
    process.exit(1);
  }
  let targets;
  try {
    targets = targetFlag !== undefined ? parseTargets(targetFlag) : await chooseTargets(cwd);
  } catch (e) {
    err(e.message);
    process.exit(1);
  }
  runSync(cwd, targets);
}

function cmdUpdate() {
  const cwd = process.cwd();
  const destAgents = path.join(cwd, '.agents');

  log(`\n🔄 agent-template update${isDryRun ? ' (dry run)' : ''}\n`);

  if (!fs.existsSync(AGENTS_SRC)) {
    err('Source .agents/ not found in package. Please reinstall.');
    process.exit(1);
  }

  if (!fs.existsSync(destAgents)) {
    warn('No .agents/ found in this project.');
    warn('Run "npx @trongtin1/agent-template init" first.');
    process.exit(0);
  }

  const srcFiles = getAllFiles(AGENTS_SRC);
  const stats = { updated: 0, skipped: 0, conflicted: 0 };
  const modifiedFiles = getGitModifiedFiles();

  for (const relFile of srcFiles) {
    const srcFile  = path.join(AGENTS_SRC, relFile);
    const destFile = path.join(destAgents, relFile);
    const relDest  = path.normalize(path.join('.agents', relFile));

    const destExists = fs.existsSync(destFile);

    if (destExists && modifiedFiles.has(relDest)) {
      // User has modified this file — save incoming copy, don't overwrite
      const incomingFile = destFile + '.incoming';
      if (!isDryRun) {
        fs.mkdirSync(path.dirname(destFile), { recursive: true });
        fs.copyFileSync(srcFile, incomingFile);
      }
      warn(`CONFLICT  .agents/${relFile}  → saved as .incoming`);
      stats.conflicted++;
    } else {
      // Safe to update
      if (!isDryRun) {
        fs.mkdirSync(path.dirname(destFile), { recursive: true });
        fs.copyFileSync(srcFile, destFile);
      }
      if (!destExists) {
        info(`NEW       .agents/${relFile}`);
      } else {
        log(`  updated  .agents/${relFile}`);
      }
      stats.updated++;
    }
  }

  log('');
  if (isDryRun) {
    info(`Dry run complete. ${stats.updated} file(s) would be updated, ${stats.conflicted} conflict(s).`);
    info('Remove --dry-run to apply changes.');
  } else {
    const statePath = path.join(cwd, STATE);
    const saved = fs.existsSync(statePath) ? JSON.parse(fs.readFileSync(statePath, 'utf8')).targets : [];
    const targets = targetFlag !== undefined ? parseTargets(targetFlag) : saved;
    if (targets.length) runSync(cwd, targets);
    else info('No IDE targets recorded. Add one with: npx @trongtin1/agent-template sync --target <ide>');
    ok(`Update complete.`);
    log(`  Updated:    ${stats.updated}`);
    log(`  Conflicts:  ${stats.conflicted}  (saved as .incoming — review and merge manually)`);
  }
  log('');
}

function cmdHelp() {
  log(`
Usage: npx @trongtin1/agent-template <command> [options]

Commands:
  init              Install .agents/ and the files for your IDE(s)
  sync              (Re)generate IDE files from .agents/ (add or change IDEs)
  update            Update .agents/ to the latest version (merge-aware) and re-sync IDEs
  update --dry-run  Preview what would change, without applying

Options:
  --target, -t <list>  Comma-separated: ${Object.keys(TARGETS).join(', ')}, all

Examples:
  npx @trongtin1/agent-template init --target claude,cursor
  npx @trongtin1/agent-template sync --target vscode
  npx @trongtin1/agent-template update
  npx @trongtin1/agent-template update --dry-run
`);
}

// ── Router ────────────────────────────────────────────────────────────────────

switch (command) {
  case 'init':   await cmdInit(); break;
  case 'sync':   await cmdSync(); break;
  case 'update': cmdUpdate(); break;
  default:       cmdHelp();
}
