import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseTargets, sync} from '../../scripts/sync_targets.mjs';

const toolkit = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

function project() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-kit-sync-'));
  fs.cpSync(toolkit, path.join(root, '.agents'), {recursive: true, filter: src => !src.endsWith('generated.json')});
  return root;
}

test('parseTargets expands all and rejects unknown names', () => {
  assert.deepEqual(parseTargets('claude,claude'), ['claude']);
  assert.equal(parseTargets('all').length, 5);
  assert.throws(() => parseTargets('foo'), /Unknown target/);
});

test('each target writes its own files only', () => {
  const root = project();
  sync(root, ['codex']);
  assert.ok(fs.existsSync(path.join(root, 'AGENTS.md')));
  assert.ok(!fs.existsSync(path.join(root, '.claude')));
  sync(root, ['cursor', 'vscode']);
  assert.ok(fs.existsSync(path.join(root, '.cursor/rules/agent-kit.mdc')));
  assert.ok(fs.existsSync(path.join(root, '.github/copilot-instructions.md')));
  assert.ok(fs.existsSync(path.join(root, 'AGENTS.md')), 'syncing other targets keeps earlier ones');
  const vscodeMcp = JSON.parse(fs.readFileSync(path.join(root, '.vscode/mcp.json'), 'utf8'));
  assert.ok(vscodeMcp.servers.context7);
});

test('files not generated by Agent Kit are never overwritten', () => {
  const root = project();
  fs.writeFileSync(path.join(root, 'AGENTS.md'), 'mine');
  const res = sync(root, ['codex']);
  assert.equal(fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8'), 'mine');
  assert.deepEqual(res.skipped, ['AGENTS.md']);
});

test('claude settings merge keeps user hooks and does not duplicate ours', () => {
  const root = project();
  fs.mkdirSync(path.join(root, '.claude'));
  fs.writeFileSync(path.join(root, '.claude/settings.json'), JSON.stringify({permissions: {allow: ['Bash(ls)']}}));
  sync(root, ['claude']);
  sync(root, ['claude']);
  const settings = JSON.parse(fs.readFileSync(path.join(root, '.claude/settings.json'), 'utf8'));
  assert.deepEqual(settings.permissions.allow, ['Bash(ls)']);
  assert.equal(settings.hooks.PreToolUse.length, 1);
});
